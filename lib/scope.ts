// ── เว็บนี้แสดงเฉพาะห้องครัว ────────────────────────────────────────────────
//
// ลูกค้าตัดขอบเขตเหลือห้องครัวอย่างเดียว ของห้องน้ำต้อง**ไม่ถูกลบ** แค่ปิดไว้
// ไฟล์นี้คือสวิตช์ตัวนั้น: เปลี่ยน KITCHEN_ONLY เป็น false แล้วของห้องน้ำกลับมา
// ครบทั้งเว็บโดยไม่ต้องกู้อะไรจาก git
//
// ── ทำไมกรองที่นี่ ไม่ใช่ลบข้อมูล ─────────────────────────────────────────
// ข้อมูลทั้งหมดอยู่ในไฟล์ *.generated.ts ซึ่งถูก **เขียนทับทุกครั้งที่ scrape ใหม่**
// ถ้าลบของห้องน้ำออกจากไฟล์พวกนั้น การ scrape รอบหน้าจะพามันกลับมาเงียบ ๆ และ
// คนที่รันสคริปต์ก็ไม่มีทางรู้ว่าเพิ่งทำอะไรพัง การกรองอยู่ที่ชั้น "หน้าร้าน"
// ซึ่งไม่มีสคริปต์ไหนแตะ กฎจึงอยู่รอดข้ามการ scrape
//
// lib/products.ts ทำแบบนี้อยู่ก่อนแล้วด้วยเหตุผลเดียวกัน ("This module stays as
// the import surface … regenerating the catalogue never touches anything but
// products.generated.ts") — ไฟล์นี้แค่ขยายรูปแบบเดิมให้ครบทุกชุดข้อมูล
//
// ── ผลที่ตามมา วัดแล้ว ไม่ใช่ประมาณ ──────────────────────────────────────
//   สินค้า        182 → 16    (ต้นทางมีห้องน้ำ 166 ห้องครัว 16)
//   เฉดผิวเคลือบ   11 → 4     (CP 8, NA 6, 0 1, BV 1 — เหลือเท่าที่ของครัวมีจริง)
//   ภาพไลฟ์สไตล์  224 → 66    (bath 158 ถูกปิด, kitchen 52 + other 14 อยู่ต่อ)
//   บทความ         10 → 3
//   คู่มือเลือกซื้อ  13 → 2
//   ไอเดีย           2 → 1
//   คอลเลกชัน      14 → 0     (การ์ดทั้ง 14 ใบเป็นชุดห้องน้ำล้วน หน้านี้จึงถูกปิดทั้งหน้า)
//
// ตัวเลข 16 คือของที่ต้นทาง kohler.co.th มีในหมวดครัว (kitchen-sinks กับ
// kitchen-faucets) ไม่ใช่ผลจาก scraper พลาด — หมวดครัวของเขามีสองหมวด ส่วน
// ห้องน้ำมีสี่

export const KITCHEN_ONLY = true;

// ── สินค้า ────────────────────────────────────────────────────────────────
/** `category` ของ lib/products.generated.ts เป็น 'kitchen' | 'bath' อยู่แล้ว */
export const allowCategory = (category: string) => !KITCHEN_ONLY || category === 'kitchen';

// ── ภาพไลฟ์สไตล์ ─────────────────────────────────────────────────────────
/**
 * `space` เป็นฟิลด์ที่ build-lifestyle.mjs จัดไว้ให้แล้ว ไม่ใช่การเดาจากชื่อไฟล์
 *
 * 'other' ผ่าน: มันคือภาพหน้าร้าน ภาพคน และภาพโปรเจกต์ ซึ่งไม่ได้เป็นของห้องไหน
 * โดยเฉพาะ ตัดทิ้งด้วยจะเหลือคลังภาพที่เล็กเกินกว่าจะจัดหน้าได้
 */
export const allowSpace = (space: string) => !KITCHEN_ONLY || space !== 'bath';

// ── เนื้อหาบรรณาธิการ ────────────────────────────────────────────────────
//
// สี่ชุดนี้ไม่มีฟิลด์บอกห้องในข้อมูล จึงเป็นรายชื่อ ไม่ใช่เงื่อนไข — และเป็นรายชื่อ
// "อะไรผ่าน" ไม่ใช่ "อะไรไม่ผ่าน" โดยตั้งใจ: ถ้า scrape รอบหน้าได้ของใหม่มา
// ของใหม่นั้นจะถูกปิดไว้จนกว่าจะมีคนดูด้วยตาแล้วเพิ่มชื่อลงมา ซึ่งปลอดภัยกว่า
// ปล่อยของที่ยังไม่มีใครดูขึ้นเว็บ

/** จาก 13 คู่มือ มีสองอันที่เป็นห้องครัว */
const KITCHEN_GUIDES = new Set(['kitchen-faucets', 'kitchen-sinks']);
export const allowGuide = (slug: string) => !KITCHEN_ONLY || KITCHEN_GUIDES.has(slug);

/**
 * จาก 8 กลุ่มสี เหลือสองกลุ่มของครัว บวกหน้าดัชนี
 *
 * 'index' ผ่านแต่ลูกของมันถูกกรองต่อด้วย allowPaletteChild — มันเป็นสารบัญ
 * ที่ชี้ไปทุกกลุ่ม ปล่อยผ่านทั้งดุ้นคือมีลิงก์ไปหน้าห้องน้ำที่ปิดไปแล้ว
 */
const KITCHEN_PALETTE = new Set(['index', 'kitchen-faucet-finishes', 'kitchen-sink-colors']);
export const allowPalette = (slug: string) => !KITCHEN_ONLY || KITCHEN_PALETTE.has(slug);

/** จาก 2 ฮับไอเดีย เหลือของครัว */
export const allowIdea = (slug: string) => !KITCHEN_ONLY || slug === 'kitchen';

/**
 * การ์ดคอลเลกชันทั้ง 14 ใบเป็นชุดห้องน้ำ — Aleutian, Archer, Cimarron, Escale,
 * FlexiSpace, Forefront, Karess, Kelston, MaxiSpace, Ove, Patio, Portrait,
 * Serif, Tresham ไม่มีใบไหนมีของครัวในแคตตาล็อกเลย หน้านี้จึงว่างทั้งหน้า
 * ไม่ใช่แค่บางการ์ดหาย — ปิดทั้งหน้าและถอดออกจากเมนู
 *
 * ชุดของครัวที่เรามีจริง (Elate, Taut, Kumin, Toccata, Marcato, Indio) ไม่มี
 * การ์ดที่ต้นทาง จะสร้างขึ้นเองก็เป็นการแต่งเนื้อหาที่ไม่มีอยู่จริง
 */
export const COLLECTIONS_ENABLED = !KITCHEN_ONLY;

/** บทความมี `space: 'bath' | 'kitchen'` ในข้อมูลอยู่แล้ว */
export const allowPost = (space: string) => !KITCHEN_ONLY || space === 'kitchen';

// ── ลิงก์ที่ชี้ไปหน้าที่ถูกปิด ───────────────────────────────────────────────
//
// หน้าที่เหลือยังมีลิงก์เก่าฝังอยู่ในข้อมูล (สารบัญของกลุ่มสี ตัวเลือกในคู่มือ
// การ์ดในฮับไอเดีย) ลิงก์พวกนั้นชี้ไปหน้าที่ไม่ถูก export แล้ว = 404
// ตัวช่วยนี้ให้ผู้เรียกกรองทิ้งก่อนวาด

const HIDDEN_PATH = /^\/(collections|palette|guides|ideas|articles|products)\//;

/**
 * href นี้ยังมีหน้าปลายทางอยู่ไหมหลังปิดของห้องน้ำ
 *
 * ตรวจเฉพาะเส้นทางที่เรารู้ว่ามีการกรอง — ลิงก์ออกนอกเว็บ ลิงก์ไป /stores/
 * /contact/ /about/ /info/ ผ่านหมดเพราะไม่มีอะไรถูกปิดในนั้น
 */
export function allowHref(href: string, resolvePath: (path: string) => boolean): boolean {
  if (!KITCHEN_ONLY) return true;
  if (!href.startsWith('/') || !HIDDEN_PATH.test(href)) return true;
  return resolvePath(href);
}

// ── หน้าข้อมูลและบริการ ───────────────────────────────────────────────────
//
// เก้าหน้าใน /info/ ไม่ใช่หน้าสินค้า มันเป็นของ KOHLER ระดับองค์กร: แคตตาล็อก PDF
// ข่าวประชาสัมพันธ์ วิธีดูแลรักษา เงื่อนไขรับประกัน หน้าพวกนี้จึงพูดถึงของห้องน้ำ
// อยู่แล้วตามธรรมชาติของมัน และตัดทั้งหน้าทิ้งก็ผิด เพราะหน้าเดียวกันพูดถึงของครัว
// ด้วย — /literature มีทั้ง "Bathtub Project Catalogue" และ "Faucets Linebook"
//
// จึงกรองเป็น "รายชิ้น" ไม่ใช่ "รายหน้า": ไทล์แคตตาล็อกและหัวข่าวที่พูดถึงของ
// ห้องน้ำโดยเฉพาะถูกปิด ส่วนชิ้นที่พูดถึงของครัวหรือพูดถึงบริษัทเฉย ๆ อยู่ต่อ
//
// ตัดสินจากข้อความที่ผู้อ่านเห็น ไม่ใช่จาก URL: ชื่อไฟล์ PDF ของ Kohler ไม่ได้
// บอกหมวดเสมอไป แต่พาดหัวที่แสดงบนหน้าบอกเสมอ

/** คำที่ทำให้ชิ้นหนึ่ง "เป็นของห้องน้ำ" — ไทยและอังกฤษ */
const BATH_WORDS =
  /ห้องน้ำ|สุขภัณฑ์|ชักโครก|โถปัสสาวะ|อ่างล้างหน้า|อ่างอาบน้ำ|ฝารองนั่ง|bathroom|bathtub|\btoilets?\b|lavator|\bbidet|urinal|sanitaryware|water closet|showerhead|\bbasins?\b/i;

/**
 * ชิ้นนี้ (ไทล์แคตตาล็อก / หัวข่าว / ลิงก์ดาวน์โหลด) ยังแสดงได้ไหม
 *
 * ── ตรวจแยกทีละภาษา ไม่ใช่เอาทุกภาษามาต่อกันแล้วตรวจครั้งเดียว ──────────
 * ข้อมูลข่าวประชาสัมพันธ์ที่ scrape มามีคู่ภาษาที่ **จับคู่ผิด**: headline.th กับ
 * headline.en ของรายการเดียวกันเป็นคนละข่าว เช่นรายการที่ .en คือ "Kohler
 * launches its most advanced toilet yet: Numi(R)" แต่ .th คือข่าวก๊อกครัว Purist
 * ถ้าต่อสองสตริงแล้วตรวจทีเดียว คำว่า kitchen ฝั่งไทยจะปล่อยข่าวชักโครกฝั่ง
 * อังกฤษผ่านไปได้ — ซึ่งเกิดขึ้นจริงสองรายการก่อนจะแก้เป็นแบบนี้
 *
 * ── ไม่มีข้อยกเว้นให้คำว่า kitchen ──────────────────────────────────────
 * เคยมี: แคตตาล็อกรวมของ Kohler ไล่หมวดทั้งบ้านในบรรทัดเดียว ("Toilets,
 * Lavatories, Bathroom Furniture, Bath, Faucets, Shower and Kitchen Sinks")
 * และการมีคำว่า Kitchen Sinks อยู่ท้ายเคยถือว่าพอให้ผ่าน ตัดข้อยกเว้นนั้นออก
 * เพราะสิ่งที่ลูกค้าขอคือ "ข้อความไหนที่เกี่ยวกับห้องน้ำให้เอาออก" — บรรทัดที่
 * ขึ้นต้นด้วย Toilets, Lavatories, Bathroom Furniture คือข้อความห้องน้ำบนหน้า
 * ไม่ว่าจะมีคำว่าครัวห้อยท้ายอยู่ด้วยหรือไม่
 *
 * หมายเหตุ: 'ฝักบัว' ไม่ได้อยู่ใน BATH_WORDS โดยตั้งใจ — ในชื่อก๊อกครัวของ Kohler
 * "หัวฝักบัว" แปลว่าหัวฉีดสายอ่อน (two-function sprayhead) ไม่ใช่ฝักบัวอาบน้ำ
 * ตัดคำนี้ทิ้งจะลบชื่อจริงของก๊อกครัวแปดตัวในแคตตาล็อก
 */
export function allowText(...parts: (string | undefined)[]): boolean {
  if (!KITCHEN_ONLY) return true;
  return parts.every((part) => !part || !BATH_WORDS.test(part));
}
