// (แก้ไปแล้วที่ต้นทางของมัน) แต่อีกส่วนหนึ่งเป็นเรื่องจริงที่แก้ไม่ได้และไม่ควรแก้:
// ชื่อร้านตัวแทนจำหน่าย ที่อยู่ ชื่อสินค้าที่ KOHLER ตีพิมพ์เป็นไทยอย่างเดียว
// และเนื้อความบทความที่ต้นทางไม่มีฉบับอังกฤษ ลูกค้ารับ fallback ไทยตรงนั้นแล้ว
//
// สิ่งที่ยังผิดอยู่คือ **มันไม่ได้บอกใครว่ามันเป็นไทย** อักษรไทยในเอกสารที่ประกาศ
// lang="en" คือข้อความที่ถูกติดป้ายผิดภาษา:
//   • screen reader อ่านอักษรไทยด้วยหน่วยเสียงอังกฤษ ซึ่งฟังไม่รู้เรื่องเลย
//   • เครื่องมือค้นหาเชื่อ lang ของเอกสาร แล้วจัดหน้านี้เป็นภาษาอังกฤษทั้งหน้า
//   • เบราว์เซอร์เลือกฟอนต์และกฎการตัดคำจากภาษาที่ประกาศไว้
//
// `lang` บน element ทับ `lang` ของ <html> เฉพาะกิ่งนั้น — จึงเป็นเครื่องมือที่ตรง
// กับปัญหาพอดี ที่เหลือของหน้ายังเป็นอังกฤษอย่างซื่อสัตย์
//
// ทำไมต้องเป็น component ไม่ใช่แค่ `lang={...}` บน element ที่มีอยู่แล้ว:
// ข้อความหลายก้อนเป็น **สองภาษาปนกันในสตริงเดียว** — ค่าสเปกอย่าง
// "H 368 มิลลิเมตร, W 60 มิลลิเมตร" หรือ "ระบบฆ่าเชื้อด้วยแสง UV และน้ำ"
// การติด lang="th" ทั้งก้อนจะบอกว่า "H", "W", "UV" เป็นภาษาไทย ซึ่งก็ผิดอีกทาง
// ที่นี่จึงห่อเฉพาะช่วงที่เป็นอักษรไทยจริง แล้วปล่อยส่วนละตินไว้ตามเดิม
//
// เมื่อภาษาของเอกสารเป็นไทยอยู่แล้ว หรือสตริงไม่มีอักษรไทยเลย component นี้คืน
// ข้อความเปล่า ๆ ไม่เพิ่ม DOM node แม้แต่ตัวเดียว — ต้นไม้ /th/ จึงไม่เปลี่ยนรูป

import { Fragment } from 'react';
import { useLang } from './LangProvider';
import { hasThai } from '@/lib/i18n';

// ช่วงอักษรไทย โดยยอมให้อักขระที่ไม่ใช่ตัวอักษรไม่เกินสามตัว (ช่องว่าง จุด
// วงเล็บ มิดดอต) เชื่อมสองช่วงเข้าด้วยกัน ไม่งั้น "เฉด CP · ราคา" จะถูกหั่นเป็น
// สาม span โดยไม่ได้ความหมายอะไรเพิ่ม
const THAI_RUN = /[฀-๿]+(?:[^฀-๿A-Za-z]{0,3}[฀-๿]+)*/g;

export default function Foreign({ children }: { children: string | null | undefined }) {
  const { lang } = useLang();
  const text = children ?? '';
  if (lang === 'th' || !text || !hasThai(text)) return <>{text}</>;

  const parts: React.ReactNode[] = [];
  let at = 0;
  for (const m of text.matchAll(THAI_RUN)) {
    const start = m.index ?? 0;
    if (start > at) parts.push(<Fragment key={`l${at}`}>{text.slice(at, start)}</Fragment>);
    parts.push(
      <span key={`t${start}`} lang="th">
        {m[0]}
      </span>,
    );
    at = start + m[0].length;
  }
  if (at < text.length) parts.push(<Fragment key={`l${at}`}>{text.slice(at)}</Fragment>);
  return <>{parts}</>;
}
